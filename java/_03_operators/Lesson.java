public class Lesson {
    public static void main(String[] args) {
        System.out.println(3 + 4);
        System.out.println(3 - 4);
        System.out.println(3 * 4);
        System.out.println(3 / 4);
        System.out.println(3 % 4);
        System.out.println(3 == 4);
        System.out.println(3 != 4);
        System.out.println(3 > 4);
        System.out.println(3 < 4);
        System.out.println(3 >= 4);
        System.out.println(3 <= 4);
        System.out.println(3 == 4 && 3 != 4);
        System.out.println(3 == 4 || 3 != 4);
        System.out.println(3 == 4 ^ 3 != 4);
        System.out.println(3 == 4 & 3 != 4);
        System.out.println(3 == 4 | 3 != 4);
    }
}
