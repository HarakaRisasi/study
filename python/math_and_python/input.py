def demo_fstring():
    """F-строки — основной способ форматированного вывода."""
    x, y = 5.76, -8
    print(f"Координаты точки: x = {x}; y = {y}")
    # Координаты точки: x = 5.76; y = -8

    # Внутри {} можно писать любые выражения Python
    print(f"Сумма: {x + y}, модуль: {abs(y)}")


