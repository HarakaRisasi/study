# ============================================================
# 4. Ввод нескольких чисел через map() и split()
# ============================================================

def demo_read_two_ints():
    """Два целых числа через пробел: '3 5' -> a=3, b=5"""
    a, b = map(int, input("Введите два целых числа: ").split())
    print(f"Сумма: {a + b}")


def demo_read_two_floats():
    """Два вещественных числа через пробел."""
    x, y = map(float, input("Введите два вещественных: ").split())
    print(f"Произведение: {x * y}")


def demo_read_three_ints():
    """Три целых числа через пробел."""
    a, b, c = map(int, input("Введите три целых: ").split())
    print(f"Периметр: {a + b + c}")


def demo_read_many_ints():
    """Произвольное количество чисел -> список."""
    lst = list(map(int, input("Введите числа через пробел: ").split()))
    print(lst)          # [1, 2, 3, 4, 5]
    print(*lst)         # 1 2 3 4 5
    print(f"Сумма: {sum(lst)}, максимум: {max(lst)}")


# ============================================================
# 5. Вывод коллекции: print(lst) vs print(*lst)
# ============================================================

def demo_print_collection():
    """Разница между выводом коллекции целиком и поэлементно."""
    lst = [1, 2, 3]
    print(lst)          # [1, 2, 3]   — как коллекция
    print(*lst)         # 1 2 3       — поэлементно через пробел

    words = ["hello", "world", "foo"]
    print(*words)       # hello world foo


# ============================================================
# 6. Периметр прямоугольника (пример из урока)
# ============================================================

def demo_rectangle_perimeter():
    """Ввод двух сторон с подсказками и вывод периметра."""
    a = float(input("Введите длину прямоугольника: "))
    b = float(input("Введите ширину прямоугольника: "))
    print("Периметр:", 2 * (a + b))


# ============================================================
# 7. Периметр прямоугольника через map (одна строка ввода)
# ============================================================

def demo_rectangle_perimeter_map():
    """Обе стороны вводятся в одной строке через пробел."""
    a, b = map(float, input("Введите две стороны прямоугольника: ").split())
    print(f"Периметр: {2 * (a + b)}")


