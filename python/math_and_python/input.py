# ============================================================
# 1. Функция print(): параметры sep и end
# ============================================================

def demo_print_sep():
    """Параметр sep задает разделитель между аргументами."""
    a, b, c = -6.84, 7, 25.6
    print(a, b, c)                    # -6.84 7 25.6 (по умолчанию пробел)
    print(a, b, c, sep=" | ")         # -6.84 | 7 | 25.6
    print(a, b, sep=" | ")            # -6.84 | 7
    # print(a, sep=" | ")             # разделять нечего — sep игнорируется


def demo_print_end():
    """Параметр end задает завершающий символ (по умолчанию '\\n')."""
    print("Hello")
    print("World!")
    # Hello
    # World!

    print("Hello", end=' ')
    print("World!")
    # Hello World!


